// Copies the engine's real recorded responses
// (services/engine/fixtures/recorded/<fixture>.<endpoint>.json) into
// src/fake/recordings/<fixture>.json, keyed by the sha256 of the fixture file
// (services/engine/tests/fixtures/<fixture>.pdf), and writes
// src/fake/recordings/index.ts. The fake engine then answers inspect, read and
// analyze exactly as the real engine did, without reading services/ at run
// time (the app's Docker build context leaves services/ out).
//
// Run after the engine lane re-records: `pnpm --filter @dueproof/engine-client recordings`.
// `--check` (run by `test`) fails if the copies are stale.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..", "..");
const recorded = join(repo, "services", "engine", "fixtures", "recorded");
const fixtures = join(repo, "services", "engine", "tests", "fixtures");
const out = join(root, "src", "fake", "recordings");
const check = process.argv.includes("--check");
if (!check) mkdirSync(out, { recursive: true });

const ENDPOINTS = ["inspect", "read", "analyze", "link"];
const names = [
  ...new Set(
    readdirSync(recorded)
      .filter((f) => f.endsWith(".json"))
      .map((f) => f.replace(/\.(inspect|read|analyze|link)\.json$/, "")),
  ),
].sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()));

const files = new Map();
for (const name of names) {
  const pdf = join(fixtures, `${name}.pdf`);
  if (!existsSync(pdf)) throw new Error(`no fixture for recording ${name}`);
  const rec = {
    name: `${name}.pdf`,
    source: `services/engine/tests/fixtures/${name}.pdf`,
    note: "Recorded from the real engine; copied by scripts/sync-recordings.mjs. Do not edit.",
    sha256: createHash("sha256").update(readFileSync(pdf)).digest("hex"),
    mime: "application/pdf",
  };
  for (const ep of ENDPOINTS) {
    const f = join(recorded, `${name}.${ep}.json`);
    if (existsSync(f)) rec[ep] = JSON.parse(readFileSync(f, "utf8"));
  }
  files.set(`${name}.json`, `${JSON.stringify(rec, null, 2)}\n`);
}

const ident = (n) =>
  n
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
    .replace(/^./, (c) => c.toLowerCase());
const index = `// Generated by scripts/sync-recordings.mjs. Do not edit.
${names.map((n) => `import ${ident(n)} from "./${n}.json" with { type: "json" };`).join("\n")}

/** Raw recordings, one per fixture; parse with \`parseRecording\`. */
export const RAW_RECORDINGS: unknown[] = [
${names.map((n) => `  ${ident(n)},`).join("\n")}
];
`;
files.set("index.ts", index);

const same = (a, b) => JSON.stringify(JSON.parse(a)) === JSON.stringify(JSON.parse(b));
const stale = [];
for (const [file, body] of files) {
  const path = join(out, file);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  // JSON is compared by value: Biome reflows the files after they are written.
  if (current === body || (current && file.endsWith(".json") && same(current, body))) continue;
  if (check) stale.push(file);
  else writeFileSync(path, body);
}
const extra = (existsSync(out) ? readdirSync(out) : []).filter((f) => !files.has(f));
if (check && (stale.length || extra.length)) {
  console.error(
    `engine recordings are stale (${[...stale, ...extra].join(", ")}): run \`pnpm --filter @dueproof/engine-client recordings\``,
  );
  process.exit(1);
}
if (!check) console.log(`synced ${names.length} recording(s)`);
