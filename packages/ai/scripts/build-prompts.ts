/**
 * Prompts are versioned markdown files in packages/ai/prompts. This script
 * expands `{{> partial}}` includes and writes src/prompts.generated.ts, so the
 * package needs no file reads at run time (works in any bundler).
 *
 *   pnpm --filter @dueproof/ai prompts          # write
 *   pnpm --filter @dueproof/ai prompts --check  # fail if out of date (CI; also a unit test)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const promptsDir = join(root, "prompts");
const outFile = join(root, "src", "prompts.generated.ts");

export interface BuiltPrompt {
  id: string;
  version: string;
  text: string;
}

function readPartial(name: string, seen: string[]): string {
  if (seen.includes(name)) throw new Error(`partial cycle: ${[...seen, name].join(" → ")}`);
  const body = readFileSync(join(promptsDir, "partials", `${name}.md`), "utf8");
  return expand(body, [...seen, name]);
}

function expand(body: string, seen: string[]): string {
  return body.replace(/\{\{>\s*([a-z0-9-]+)\s*\}\}/g, (_m, name: string) =>
    readPartial(name, seen).trimEnd(),
  );
}

export function buildPrompts(): Record<string, BuiltPrompt> {
  const out: Record<string, BuiltPrompt> = {};
  for (const file of readdirSync(promptsDir).sort()) {
    if (!file.endsWith(".md")) continue;
    const raw = readFileSync(join(promptsDir, file), "utf8");
    const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
    if (!m) throw new Error(`${file}: missing front matter`);
    const meta = Object.fromEntries(
      (m[1] ?? "")
        .split("\n")
        .filter((l) => l.includes(":"))
        .map((l) => {
          const i = l.indexOf(":");
          return [l.slice(0, i).trim(), l.slice(i + 1).trim()];
        }),
    );
    if (!meta.id || !meta.version) throw new Error(`${file}: front matter needs id and version`);
    if (out[meta.id]) throw new Error(`${file}: duplicate prompt id ${meta.id}`);
    out[meta.id] = {
      id: meta.id,
      version: meta.version,
      text: `${expand(m[2] ?? "", []).trim()}\n`,
    };
  }
  return out;
}

export function renderGenerated(prompts: Record<string, BuiltPrompt>): string {
  return `// Generated by scripts/build-prompts.ts from packages/ai/prompts/*.md. Do not edit.\nexport const PROMPTS = ${JSON.stringify(prompts, null, 2)} as const;\n`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const built = buildPrompts();
  const text = renderGenerated(built);
  if (process.argv.includes("--check")) {
    // Compare data, not text: the formatter may restyle the generated file.
    const { PROMPTS } = await import("../src/prompts.generated");
    if (JSON.stringify(PROMPTS) !== JSON.stringify(built)) {
      console.error(
        "src/prompts.generated.ts is out of date: run `pnpm --filter @dueproof/ai prompts`",
      );
      process.exit(1);
    }
    console.log("prompts up to date");
  } else {
    writeFileSync(outFile, text);
    console.log(`wrote ${outFile}`);
  }
}
