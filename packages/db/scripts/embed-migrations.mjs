// Embeds migrations/*.sql (Drizzle's journal order) and migrations/rls.sql into
// src/migrations.gen.ts, so `migrate()` works the same from a Next.js bundle,
// the desktop sidecar and tests, without reading files at run time.
//
// Run after `drizzle-kit generate`: `pnpm --filter @dueproof/db db:generate`
// does both. `pnpm --filter @dueproof/db db:check` fails if the file is stale.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "migrations");
const journal = JSON.parse(readFileSync(join(dir, "meta", "_journal.json"), "utf8"));

const migrations = journal.entries.map((entry) => {
  const query = readFileSync(join(dir, `${entry.tag}.sql`), "utf8");
  return {
    tag: entry.tag,
    folderMillis: entry.when,
    // Same hash Drizzle's readMigrationFiles() records.
    hash: createHash("sha256").update(query).digest("hex"),
    bps: entry.breakpoints,
    sql: query.split("--> statement-breakpoint"),
  };
});
const rls = readFileSync(join(dir, "rls.sql"), "utf8").split("--> statement-breakpoint");

const raw = `// Generated by scripts/embed-migrations.mjs. Do not edit.
export interface EmbeddedMigration {
  tag: string;
  folderMillis: number;
  hash: string;
  bps: boolean;
  sql: string[];
}

export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};

export const RLS_SQL: string[] = ${JSON.stringify(rls, null, 2)};
`;

const target = join(root, "src", "migrations.gen.ts");
// Format with the repo's Biome so `pnpm lint` stays green on the generated file.
const out = execFileSync(
  "pnpm",
  ["exec", "biome", "format", "--stdin-file-path=src/migrations.gen.ts"],
  {
    cwd: root,
    input: raw,
    encoding: "utf8",
    stdio: ["pipe", "pipe", "ignore"],
  },
);
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) {
    console.error("src/migrations.gen.ts is stale: run `pnpm --filter @dueproof/db db:generate`");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`embedded ${migrations.length} migration(s) and rls.sql`);
}
